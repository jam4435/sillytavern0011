import re
t=open('批次F/F1-笑傲第1-20回.md',encoding='utf-8').read()
pat=re.compile(r"### EV-笑傲-(d{4}) · ")
cards=[]
idx=[(m.start(),m.group(1)) for m in pat.finditer(t)]
for i,(s,eid) in enumerate(idx):
    end = idx[i+1][0] if i+1<len(idx) else len(t)
    cards.append([eid, t[s:end]])
def rep(eid, newpos, newex):
    for c in cards:
        if c[0]==eid:
            body=c[1]
            body=re.sub(r"^- 原文位置: .*$", "- 原文位置: "+newpos, body, count=1, flags=re.M)
            body=re.sub(r"^- 原文摘录: .*$", "- 原文摘录: "+newex, body, count=1, flags=re.M)
            c[1]=body
            print('patched',eid)
            return
    print('NOT FOUND',eid)
