// 构造 sects.json
const sects = raw.门派列表.map(m => {
  const meta = FACTION_METAS[m.门派] || {
    体系类型: m.体系类型 === '军旅' ? '行伍' : m.体系类型 === '帮会' ? '帮会' : m.体系类型.includes('家传') || m.体系类型.includes('庄门') ? '世家' : '宗门',
    主峰驻地: '大宋/终南山/重阳宫',
    掌舵人: m.人物映射边界.filter(p => p.关系类型.includes('掌') || p.关系类型.includes('主') || p.关系类型.includes('尊')).map(p => p.角色).slice(0, 3),
    入门门槛: { 最低境界: '无', 属性要求: {} },
    特色描述: m.设计定位,
  };

  // 整理传承武学节点
  const martialNodes = m.传承节点.map(n => ({
    节点ID: n.节点ID,
    功法: n.功法,
    传承层级: n.传承层级, // '入门' | '基础' | '进阶' | '核心' | '镇派'
    分支: n.分支,
    是否共通: Boolean(n.是否共通),
    前置节点: (n.前置节点 || []).map(p => ({
      节点ID: p.节点ID,
      最低掌握程度: p.最低掌握程度,
      关系: p.关系,
    })),
    学习限制: {
      最低传承资格: n.学习限制?.最低传承资格 || '门内通传',
      最低境界: n.学习限制?.最低境界 || '无',
      属性门槛: n.学习限制?.属性门槛 || {},
      特别条件: n.学习限制?.特别条件 || [],
    },
  }));

  return {
    门派ID: m.门派ID,
    门派名称: m.门派,
    门派别名: m.门派别名 || [],
    体系类型: meta.体系类型,
    主峰驻地: meta.主峰驻地,
    掌舵人: meta.掌舵人,
    设计定位: m.设计定位,
    特色描述: meta.特色描述,
    入门门槛: meta.入门门槛,
    人物映射边界: m.人物映射边界.map(p => ({
      角色: p.角色,
      关系类型: p.关系类型,
      最高可分配层级: p.最高可分配层级,
    })),
    武学传承树: martialNodes,
  };
});

const output = {
  version: 1,
  totalSects: sects.length,
  sects,
};

const targetPath = path.resolve('src/武侠/data/sects.json');
fs.writeFileSync(targetPath, JSON.stringify(output, null, 2), 'utf8');
console.log(`成功生成 sects.json，包含 ${sects.length} 个势力与全部武学节点！输出至: ${targetPath}`);
