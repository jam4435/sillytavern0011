import { describe, expect, it } from 'vitest';
import { setMartialArtsDatabase } from './martialArtsDatabase';
import {
  buildCombatPowerZoneFromStatData,
  buildCultivationChangeReferenceFromStatData,
  buildFrontendRandomNumbers,
} from './frontendDerivedVariables';

describe('frontendDerivedVariables', () => {
  it('按稀疏行生成战力区，并且只纳入严格同三级地点的人物', () => {
    setMartialArtsDatabase([
      {
        功法名称: '凌波微步',
        类型: '轻功',
        功法品阶: '绝世',
        功法描述: '测试轻功',
        战斗系数: {
          属性列表: [
            { 属性: '机敏', 系数: 0.8 },
            { 属性: '悟性', 系数: 0.3, 乘境界: true },
          ],
        },
      },
      {
        功法名称: '水上漂',
        类型: '轻功',
        功法品阶: '上乘',
        功法描述: '测试轻功',
        战斗系数: {
          属性列表: [
            { 属性: '机敏', 系数: 0.5 },
            { 属性: '洞察', 系数: 0.4 },
          ],
        },
      },
      {
        功法名称: '降龙十八掌',
        类型: '拳掌',
        功法品阶: '传说',
        功法描述: '测试掌法',
        战斗系数: {
          属性列表: [
            { 属性: '臂力', 系数: 0.8 },
            { 属性: '根骨', 系数: 0.4 },
            { 属性: '机敏', 系数: 0.3 },
          ],
        },
      },
      {
        功法名称: '劈空掌',
        类型: '拳掌',
        功法品阶: '上乘',
        功法描述: '测试掌法',
        战斗系数: {
          属性列表: [{ 属性: '臂力', 系数: 0.4 }],
        },
      },
    ]);

    const table = buildCombatPowerZoneFromStatData({
      user数据: {
        用户名: '少侠',
        所在位置: '大宋/临安府/牛家村/村西树林',
        境界: '三流-初期',
        初始属性: {
          臂力: 10,
          根骨: 9,
          机敏: 8,
          悟性: 7,
          洞察: 6,
          风姿: 5,
          福缘: 4,
        },
        功法: {
          凌波微步: { 掌握程度: '炉火纯青' },
          水上漂: { 掌握程度: '融会贯通' },
          降龙十八掌: { 掌握程度: '融会贯通' },
          劈空掌: { 掌握程度: '初窥门径' },
        },
      },
      角色数据: {
        洪七公: {
          所在位置: '大宋/临安府/牛家村/曲三酒馆',
          境界: '三流-初期',
          初始属性: {
            臂力: 9,
            根骨: 8,
            机敏: 7,
            悟性: 6,
            洞察: 5,
          },
          功法: {
            降龙十八掌: { 掌握程度: '炉火纯青' },
          },
        },
        黄蓉: {
          所在位置: '大宋/临安府/西湖',
          境界: '三流-初期',
          初始属性: {
            臂力: 6,
            根骨: 6,
            机敏: 9,
            悟性: 10,
            洞察: 10,
          },
          功法: {
            凌波微步: { 掌握程度: '融会贯通' },
          },
        },
      },
    });

    expect(table).toBe(
      [
        '少侠|位置:大宋/临安府/牛家村/村西树林|基础:50|轻功:凌波微步=85;水上漂=64|拳掌:降龙十八掌=140;劈空掌=40',
        '洪七公|位置:大宋/临安府/牛家村/曲三酒馆|基础:44|拳掌:降龙十八掌=125',
      ].join('\n'),
    );
    expect(table).not.toContain('黄蓉');
  });

  it('按固定格式生成五个随机数字符串', () => {
    const randomNumbers = buildFrontendRandomNumbers();
    const lines = randomNumbers.split('\n');

    expect(lines).toHaveLength(5);
    lines.forEach((line, index) => {
      expect(line).toMatch(new RegExp(`^随机数${index + 1}: (10|[0-9])$`));
    });
  });

  it('按最高有效内功生成修为变化参考，不叠加多门内功', () => {
    setMartialArtsDatabase([
      {
        功法名称: '九阳神功',
        类型: '内功',
        功法品阶: '上乘',
        功法描述: '测试内功',
      },
      {
        功法名称: '抱元劲',
        类型: '内功',
        功法品阶: '粗浅',
        功法描述: '测试内功',
      },
      {
        功法名称: '凌波微步',
        类型: '轻功',
        功法品阶: '传说',
        功法描述: '测试轻功',
      },
    ]);

    expect(
      buildCultivationChangeReferenceFromStatData({
        user数据: {
          境界: '三流初期',
          初始属性: { 悟性: 10 },
          功法: {
            九阳神功: { 掌握程度: '融会贯通' },
            抱元劲: { 掌握程度: '出神入化' },
            凌波微步: { 掌握程度: '出神入化' },
          },
        },
      }),
    ).toBe(14);
  });

  it('没有显性内功时使用境界隐含保底生成修为变化参考', () => {
    setMartialArtsDatabase([]);

    expect(
      buildCultivationChangeReferenceFromStatData({
        user数据: {
          境界: '一流初期',
          初始属性: { 悟性: 10 },
          功法: {},
        },
      }),
    ).toBe(40);
  });

  it('玩家战力区会读取装备栏和状态效果的属性修正', () => {
    setMartialArtsDatabase([
      {
        功法名称: '劈空掌',
        类型: '拳掌',
        功法品阶: '上乘',
        功法描述: '测试掌法',
        战斗系数: {
          属性列表: [{ 属性: '臂力', 系数: 1 }],
        },
      },
    ]);

    const table = buildCombatPowerZoneFromStatData({
      user数据: {
        用户名: '少侠',
        所在位置: '大宋/临安府/牛家村',
        境界: '不入流',
        初始属性: {
          臂力: 10,
          根骨: 10,
          机敏: 10,
          悟性: 10,
          洞察: 10,
          风姿: 10,
          福缘: 0,
        },
        功法: {
          劈空掌: { 掌握程度: '初窥门径' },
        },
        包裹: {
          铁护腕: {
            类型: '装备',
            品阶: '绝品',
            部位: '护腕',
            属性修正: { 臂力: 50 },
          },
        },
        装备栏: {
          护腕: '铁护腕',
        },
        状态效果: {
          药效一: {
            类型: '药品',
            功效类型: '临时增幅',
            来源: '大力丸',
            品阶: '珍品',
            属性修正: { 臂力: 30 },
            持续时间: 3,
            剩余时间: 2,
          },
        },
      },
    });

    expect(table).toBe('少侠|位置:大宋/临安府/牛家村|基础:0|拳掌:劈空掌=18');
  });

  it('玩家战力区会读取聊天分支中的奇经八脉修正', () => {
    setMartialArtsDatabase([
      {
        功法名称: '劈空掌',
        类型: '拳掌',
        功法品阶: '上乘',
        功法描述: '测试掌法',
        战斗系数: { 属性列表: [{ 属性: '臂力', 系数: 1 }] },
      },
    ]);

    const table = buildCombatPowerZoneFromStatData({
      user数据: {
        用户名: '少侠',
        所在位置: '大宋/临安府/牛家村',
        境界: '不入流',
        初始属性: { 臂力: 10, 根骨: 10, 机敏: 10, 悟性: 10, 洞察: 10, 风姿: 10, 福缘: 0 },
        功法: { 劈空掌: { 掌握程度: '初窥门径' } },
      },
      前端变量: {
        奇经八脉: {
          版本: 1,
          已通穴位: ['du:opening', 'du:circulation', 'du:condensation', 'du:cycle'],
          关窍结算: {},
        },
      },
    });

    expect(table).toBe('少侠|位置:大宋/临安府/牛家村|基础:0|拳掌:劈空掌=11');
  });

  it('没有具名功法时按结算后战斗属性提供境界基础招式保底', () => {
    setMartialArtsDatabase([]);

    const table = buildCombatPowerZoneFromStatData({
      user数据: {
        用户名: '高手',
        所在位置: '大宋/临安府/牛家村',
        境界: '一流-初期',
        初始属性: {
          臂力: 10,
          根骨: 10,
          机敏: 10,
          悟性: 10,
          洞察: 10,
          风姿: 10,
          福缘: 0,
        },
        功法: {},
      },
    });

    expect(table).toMatch(/^高手\|位置:大宋\/临安府\/牛家村\|基础:[1-9]\d*$/);
    expect(table).not.toContain('无');
  });
});
