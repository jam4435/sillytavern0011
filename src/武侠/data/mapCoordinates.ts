export function clampMapCoordinate(coordinate: MapCoordinate): MapCoordinate {
  return {
    x: Math.max(32, Math.min(MAP_WIDTH - 32, Math.round(coordinate.x))),
    y: Math.max(32, Math.min(MAP_HEIGHT - 32, Math.round(coordinate.y))),
  };
}
