export function getImportantLocationLore(scopePath: string): ImportantLocationLore | null {
  return IMPORTANT_LOCATION_LORE[scopePath] ?? null;
}

export function buildCurrentLocationLoreVariable(
  location: string,
): CurrentLocationLoreVariable | null {
  const normalized = location.trim().replace(/[\\＞>›→]+/g, '/');
  const segments = normalized.split('/').map(part => part.trim()).filter(Boolean);
  if (segments.length < 3) return null;
  const scopePath = segments.slice(0, 3).join('/');
  const lore = getImportantLocationLore(scopePath);
  return lore ? { 严格活动区: scopePath, ...lore } : null;
}
